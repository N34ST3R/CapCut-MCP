"""Derive sanitized schema templates from projects written by the installed CapCut build.

CapCut has no public API, so drafts are generated by matching the on-disk schema that
the local app version writes. This script reads existing drafts once and emits:

  capcut_mcp/templates/draft_base.json   empty timeline skeleton for the same version
  capcut_mcp/templates/prototypes.json   material/segment/track prototypes

Machine-specific and user-specific values (ids, media paths, device ids, font paths)
are stripped; the engine fills them per project. Re-run after a CapCut upgrade:

    python tools/extract_templates.py
"""

from __future__ import annotations

import argparse
import copy
import json
import os
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
PKG = HERE.parent / "capcut_mcp"
TEMPLATES = PKG / "templates"
DRAFTS_ROOT = Path(
    os.environ.get("CAPCUT_DRAFTS_DIR")
    or Path(os.environ["LOCALAPPDATA"]) / "CapCut" / "User Data" / "Projects" / "com.lveditor.draft"
)

# Fields that hold machine/user state or media-specific values.
SCRUB_KEYS = {
    "id",
    "path",
    "media_path",
    "reverse_path",
    "reverse_intensifies_path",
    "intensifies_path",
    "intensifies_audio_path",
    "cartoon_path",
    "material_url",
    "request_id",
    "local_material_id",
    "origin_material_id",
    "team_id",
    "unique_id",
    "local_id",
    "check_flag",
    "extra_material_refs",
    "common_keyframes",
    "keyframe_refs",
    "raw_segment_id",
    "material_id",
    "extra_material_ids",
    "matrix_path",
    "font_path",
}


def scrub(value):
    """Blank machine-specific leaves while keeping the key structure intact."""
    if isinstance(value, dict):
        out = {}
        for k, v in value.items():
            if k in SCRUB_KEYS:
                out[k] = "" if not isinstance(v, (list, dict)) else type(v)()
            elif k == "content" and isinstance(v, str) and v.strip().startswith("{"):
                out[k] = ""  # text content is rebuilt by the engine
            else:
                out[k] = scrub(v)
        return out
    if isinstance(value, list):
        return [scrub(v) for v in value]
    return value


def load_draft(folder: Path) -> dict:
    with open(folder / "draft_content.json", encoding="utf-8") as fh:
        return json.load(fh)


def index_materials(draft: dict) -> dict[str, tuple[str, dict]]:
    idx: dict[str, tuple[str, dict]] = {}
    for kind, items in draft.get("materials", {}).items():
        for item in items:
            idx[item.get("id", "")] = (kind, item)
    return idx


def find_empty_draft(candidates: list[Path]) -> tuple[Path, dict] | None:
    for folder in candidates:
        try:
            draft = load_draft(folder)
        except Exception:
            continue
        if not draft.get("tracks") and not any(draft.get("materials", {}).values()):
            return folder, draft
    return None


def first_segment(draft: dict, track_type: str) -> dict | None:
    for track in draft.get("tracks", []):
        if track.get("type") == track_type and track.get("segments"):
            return track["segments"][0]
    return None


def first_track(draft: dict, track_type: str) -> dict | None:
    for track in draft.get("tracks", []):
        if track.get("type") == track_type:
            return track
    return None


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--source", help="draft folder to read prototypes from (auto-detected by default)")
    args = ap.parse_args()

    if not DRAFTS_ROOT.is_dir():
        print(f"CapCut drafts folder not found: {DRAFTS_ROOT}", file=sys.stderr)
        return 2

    folders = [
        p for p in DRAFTS_ROOT.iterdir()
        if p.is_dir() and (p / "draft_content.json").is_file() and not p.name.startswith(".")
    ]
    folders.sort(key=lambda p: (p / "draft_content.json").stat().st_mtime, reverse=True)

    if args.source:
        folders = [Path(args.source)] + [f for f in folders if f != Path(args.source)]

    # No single project necessarily contains every material type, so prototypes are
    # merged across all populated projects (newest first) instead of trusting one.
    populated: list[tuple[Path, dict]] = []
    for folder in folders:
        try:
            draft = load_draft(folder)
        except Exception:
            continue
        if draft.get("tracks") and any(draft.get("materials", {}).values()):
            populated.append((folder, draft))

    # CapCut stamps its platform block with a device id; drafts written by this
    # generator leave it blank. Only learn shapes from real app output, otherwise
    # repeated runs slowly learn the generator's own approximations.
    app_written = [
        (folder, draft)
        for folder, draft in populated
        if (draft.get("platform") or {}).get("device_id")
    ]
    if app_written:
        populated = app_written

    if not populated:
        print("No populated CapCut project found; cannot derive prototypes.", file=sys.stderr)
        return 3

    empty = find_empty_draft(folders)
    empty_draft = empty[1] if empty else None
    base_source = empty_draft if empty_draft else populated[0][1]
    base = scrub(copy.deepcopy(base_source))

    # A skeleton must start clean: no tracks, no materials, zero duration.
    base["tracks"] = []
    base["duration"] = 0
    base["canvas_config"] = {"ratio": "original", "width": 1920, "height": 1080, "background": None}
    base["keyframes"] = {k: [] for k in base.get("keyframes", {})} or {}
    for kind in list(base.get("materials", {})):
        base["materials"][kind] = []

    # Platform blocks carry device identifiers; rebuild them without any. Prefer the
    # newest writer (the empty draft) over an older project's stale version string.
    src_platform = base.get("platform") or populated[0][1].get("platform") or {}
    clean_platform = {
        "os": src_platform.get("os", "windows"),
        "os_version": "",
        "app_id": src_platform.get("app_id", 359289),
        "app_version": src_platform.get("app_version", ""),
        "app_source": src_platform.get("app_source", "cc"),
        "device_id": "",
        "hard_disk_id": "",
        "mac_address": "",
    }
    base["platform"] = dict(clean_platform)
    base["last_modified_platform"] = dict(clean_platform)

    array_for = {"video": "videos", "photo": "videos", "audio": "audios", "text": "texts"}
    materials: dict[str, dict | None] = {kind: None for kind in array_for}
    segments: dict[str, dict | None] = {kind: None for kind in ("video", "audio", "text")}
    tracks: dict[str, dict | None] = {kind: None for kind in ("video", "audio", "text")}
    companions: dict[str, dict] = {}
    used: list[str] = []

    for folder, draft in populated:
        contributed = False
        for kind, array in array_for.items():
            items = draft.get("materials", {}).get(array) or []
            if materials[kind] is None and items:
                # images and videos share the arrays; the type field discriminates.
                wanted = items[0]
                if kind in ("video", "photo"):
                    wanted = next((item for item in items if item.get("type") == kind), None)
                if wanted:
                    materials[kind] = scrub(copy.deepcopy(wanted))
                    contributed = True
            if kind not in segments:
                continue
            if segments[kind] is None:
                segment = first_segment(draft, kind)
                if segment:
                    segments[kind] = scrub(copy.deepcopy(segment))
                    contributed = True
            if tracks[kind] is None:
                track = first_track(draft, kind)
                if track:
                    tracks[kind] = scrub(copy.deepcopy(track))
                    contributed = True

        index = index_materials(draft)
        # Companions are attached per segment type, so walk every populated segment.
        for track in draft.get("tracks", []):
            for segment in track.get("segments", []):
                for ref in segment.get("extra_material_refs", []):
                    kind, material = index.get(ref, (None, None))
                    if kind and kind not in companions and material:
                        companions[kind] = scrub(copy.deepcopy(material))
                        contributed = True
        if contributed:
            used.append(folder.name)

    prototypes = {
        "generator": "extract_templates.py",
        "capcut_version": base.get("platform", {}).get("app_version", ""),
        "schema_version": base.get("new_version", ""),
        "source_projects": used,
        "extracted_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
        # Still images are stored in materials.videos with type "photo"; there is no
        # separate image array in CapCut International drafts.
        "materials": materials,
        "companions": companions,
        "segments": segments,
        "tracks": tracks,
    }

    TEMPLATES.mkdir(parents=True, exist_ok=True)
    # Metadata sidecar skeleton (draft_meta_info.json), stripped of ids/paths/times.
    meta_template: dict = {}
    meta_src = (empty[0] / "draft_meta_info.json") if empty else (populated[0][0] / "draft_meta_info.json")
    if meta_src.is_file():
        meta_template = json.loads(meta_src.read_text(encoding="utf-8"))
    meta_template.update(
        draft_fold_path="",
        draft_id="",
        draft_name="",
        draft_root_path="",
        draft_cover="",
        tm_draft_create=0,
        tm_draft_modified=0,
        tm_duration=0,
        draft_materials=[{"type": t, "value": []} for t in (0, 1, 2, 3, 6)],
        draft_materials_copied_info=[],
        draft_segment_extra_info=[],
        draft_timeline_materials_size_=0,
    )

    (TEMPLATES / "draft_meta_info.json").write_text(
        json.dumps(meta_template, indent=1, ensure_ascii=False), encoding="utf-8"
    )
    (TEMPLATES / "draft_base.json").write_text(json.dumps(base, indent=1, ensure_ascii=False), encoding="utf-8")
    (TEMPLATES / "prototypes.json").write_text(
        json.dumps(prototypes, indent=1, ensure_ascii=False), encoding="utf-8"
    )

    missing = [k for k, v in prototypes["materials"].items() if not v]
    print(f"source projects: {', '.join(used)}")
    print(f"capcut version : {prototypes['capcut_version']} (schema {prototypes['schema_version']})")
    print(f"base skeleton  : {'empty project' if empty else 'derived from newest project'}")
    print(f"prototypes     : {', '.join(k for k, v in prototypes['materials'].items() if v)}")
    print(f"segments       : {', '.join(k for k, v in prototypes['segments'].items() if v)}")
    if missing:
        print(f"missing        : {', '.join(missing)} (those tools will report unsupported)", file=sys.stderr)
    print(f"written        : {TEMPLATES}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
